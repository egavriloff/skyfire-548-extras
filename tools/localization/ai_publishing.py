"""Explicit publication of a fresh VALID-only AI layer, separate from donors."""
from collections import Counter
import copy
import hashlib
from pathlib import Path
import tempfile

import ai_fallback as ai
import publishing as p


def prepare(api, conn, directory, locale):
    """Revalidate against the current index and verify every staged byte."""
    path = directory / 'custom/manifest.json'
    if not path.is_file() or path.is_symlink() or (directory/'custom').is_symlink():
        raise ValueError('AI custom manifest missing/unsafe; run ai-validate --write-sql first')
    manifest = ai.read_json(path)
    report = ai.validate_results(api, conn, directory, locale)
    valid = sorted((r for r in report['results'] if r['status'] == 'VALID'), key=ai.order)
    rejected = [r for r in report['results'] if r['status'] != 'VALID']
    expected = {'version': ai.VERSION, 'locale': locale, 'target': ai.TARGET, 'layer': 'ai_custom',
                'approved': False, 'summary': report['summary'], 'entries': valid,
                'rejected': rejected, 'source_evidence': report['source_evidence']}
    for name, value in expected.items():
        if manifest.get(name) != value:
            raise ValueError('Stale/changed AI custom manifest: ' + name + '; run ai-validate --write-sql')
    for name, file in [('requests_sha256','requests.jsonl'),
                       ('requests_manifest_sha256','requests-manifest.json'),
                       ('translations_sha256','translations.jsonl')]:
        if manifest.get(name) != p.digest(directory / file):
            raise ValueError('Stale AI input hash: ' + file)
    if not valid or len({ai.identity(r) for r in valid}) != len(valid):
        raise ValueError('AI layer has no VALID fields or duplicate field identities')
    files = {}
    hashes = {}
    for kind in ai.KINDS:
        rows = [r for r in valid if r['entity'] == kind]
        name = kind + '.sql'
        source = directory / 'custom' / name
        text = ai.custom_sql_text(api, kind, locale, rows)
        if source.is_symlink() or not source.is_file() or source.read_bytes() != text.encode('utf-8'):
            raise ValueError('Missing/changed AI SQL: ' + name + '; run ai-validate --write-sql')
        hashes[name] = p.digest(source)
        statements = ''.join(ai.sql_statement(api, r, locale) + '\n' for r in rows)
        header = (f'-- SkyFire 5.4.8 {locale} AI/custom fallback.\n'
                  '-- Generated by tools/localization; see manifest.json for provenance.\n'
                  '-- Apply donor SQL first; existing nonempty translations are preserved.\n')
        files['custom/' + name] = (header + statements).encode('utf-8')
    if manifest.get('files') != hashes:
        raise ValueError('AI SQL file hashes do not match custom manifest')
    metadata = {k: copy.deepcopy(manifest[k]) for k in
                ('version','locale','target','layer','summary','entries','source_evidence',
                 'requests_sha256','requests_manifest_sha256','translations_sha256')}
    metadata.update(published=True, publication='explicit_publish_include_ai', donor_evidence=False,
                    staged_manifest_sha256=p.digest(path),
                    excluded_reasons=dict(sorted(Counter(r['reason'] for r in rejected).items())),
                    fields_by_entity=dict(sorted(Counter(r['entity'] for r in valid).items())),
                    rows_by_entity={k: len({ai.encoded(r['key']) for r in valid if r['entity']==k}) for k in ai.KINDS},
                    files={name.removeprefix('custom/'):hashlib.sha256(data).hexdigest() for name,data in files.items()})
    return {'files':files, 'metadata':metadata}


def retained_files(output, manifest):
    """Preserve an existing separate layer on ordinary donor-only publication."""
    layer = manifest.get('layers', {}).get('ai_custom')
    if not layer:
        return {}
    allowed = {'custom/' + k + '.sql' for k in ai.KINDS} | {'custom/manifest.json'}
    files = layer.get('files')
    if not isinstance(files,dict) or set(files) != allowed:
        raise ValueError('Invalid published AI file list')
    for name, sha in files.items():
        file = output / name
        if (file.is_symlink() or (output/'custom').is_symlink() or not file.is_file()
                or output.resolve() not in file.resolve().parents or p.digest(file) != sha
                or manifest.get('files',{}).get(name) != sha):
            raise ValueError('Published AI file does not match metadata: ' + name)
    return files


def stage_layer(staging, files, manifest, payload):
    hashes = {}
    for name, data in payload['files'].items():
        file = staging / name; file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(data); files[name]=file; hashes[name]=p.digest(file)
    metadata = payload['metadata']
    path = staging / 'custom/manifest.json'
    p.write_json(path, metadata); files['custom/manifest.json']=path
    hashes['custom/manifest.json']=p.digest(path)
    manifest.setdefault('layers',{})['ai_custom'] = {'files':hashes, 'summary':metadata['summary'],
        'fields_by_entity':metadata['fields_by_entity'], 'donor_evidence':False,
        'provenance_manifest':'custom/manifest.json'}


def complete(staging, files, manifest):
    layer=manifest.get('layers',{}).get('ai_custom')
    if not layer:
        return
    readme=staging/'README.md'
    text=readme.read_text(encoding='utf-8')
    text += ('\n## Separate AI fallback layer\n\n'
             'The donor coverage above excludes AI-generated fields. This optional layer\n'
             'contains only mechanically VALID translations, with separate provenance in\n'
             '`custom/manifest.json`. Validation does not guarantee linguistic quality.\n\n'
             '| Entity | AI fields |\n| --- | ---: |\n')
    for kind, count in sorted(layer['fields_by_entity'].items()):
        text += f'| {kind} | {count:,} |\n'
    text += (f"| TOTAL | {layer['summary']['valid']:,} |\n\n"
             f"Excluded invalid AI fields: {layer['summary']['invalid']:,}.\n\n"
             'Apply the root donor SQL first, then the SQL under `custom/`. The exact\n'
             'file sequence and hashes are recorded in `manifest.json` as\n'
             '`application_order` and `files`. Existing nonempty values remain protected.\n')
    readme.write_text(text,encoding='utf-8',newline='\n')
    manifest['files'].update(layer['files'])
    manifest['files']['README.md']=p.digest(readme)
    donor=sorted({name for e in manifest['entities'].values() for name in e['files']})
    manifest['application_order']=donor+sorted(name for name in layer['files'] if name.endswith('.sql'))


def replace_staged(output, files):
    for name in files:
        dest=output/name
        if dest.is_symlink() or output.resolve() not in dest.resolve().parents:
            raise ValueError('Unsafe publication destination: ' + str(dest))
        if any(parent.is_symlink() for parent in dest.parents if parent != output.parent):
            raise ValueError('Symlink in publication path: ' + str(dest))
    for name, file in files.items():
        (output/name).parent.mkdir(parents=True,exist_ok=True)
        file.replace(output/name)


def publish_existing(output, locale, specs, payload):
    """Extend the verified published donor snapshot; never approve a new review."""
    path=output/'manifest.json'
    if output.is_symlink() or not path.is_file() or path.is_symlink():
        raise ValueError('AI-only publish requires an existing verified donor publication')
    manifest=ai.read_json(path)
    if (manifest.get('version')!=1 or manifest.get('locale')!=locale
            or manifest.get('target')!='SkyFire 5.4.8 World DB' or not manifest.get('entities')):
        raise ValueError('Invalid existing donor publication')
    retained_files(output,manifest)
    expected={'README.md'}
    for kind, data in manifest['entities'].items():
        if kind not in specs or not data.get('review_bundle_sha256') or not data.get('review_report_sha256'):
            raise ValueError('Published donor review metadata missing: ' + kind)
        counts=data.get('summary',{})
        if (not counts or any(type(v) is not int or v<0 for v in counts.values())
                or counts.get('total_target_entities')!=counts.get('exported',0)+counts.get('skipped',0)):
            raise ValueError('Invalid saved donor counters: ' + kind)
        allowed={kind+'.sql'} | ({'quest_objective.sql'} if kind=='quest' else set())
        if not data.get('files') or not set(data['files'])<=allowed:
            raise ValueError('Unsafe donor file set: ' + kind)
        for name,sha in data['files'].items():
            if manifest['files'].get(name)!=sha:
                raise ValueError('Donor metadata hash disagreement: ' + name)
            expected.add(name)
    expected.update(manifest.get('layers',{}).get('ai_custom',{}).get('files',{}))
    if set(manifest.get('files',{}))!=expected:
        raise ValueError('Published file set does not match donor/layer metadata')
    for name,sha in manifest['files'].items():
        f=output/name
        if f.is_symlink() or not f.is_file() or output.resolve() not in f.resolve().parents or p.digest(f)!=sha:
            raise ValueError('Published donor snapshot changed: ' + name)
    with tempfile.TemporaryDirectory(dir=output.parent) as temporary:
        staging=Path(temporary);files={}
        stage_layer(staging,files,manifest,payload)
        readme=staging/'README.md'
        readme.write_text(p.coverage_readme(locale,manifest['target'],{k:v['summary'] for k,v in manifest['entities'].items()}),encoding='utf-8',newline='\n')
        files['README.md']=readme
        complete(staging,files,manifest)
        p.write_json(staging/'manifest.json',manifest);files['manifest.json']=staging/'manifest.json'
        replace_staged(output,files)
    return {'entities':[], 'donors':'retained_verified_publication', 'ai_fields':payload['metadata']['summary']['valid'], 'files':sorted(files)}
